def build_small():
    cw, chh = 8, 10
    cols = 16
    rows_n = (len(CHARS) + cols - 1) // cols
    sheet = np.zeros((rows_n * chh, cols * cw, 4), np.uint8)
    widths = []
    for i, ch in enumerate(CHARS):
        top = None
        if ch in S5_TOP:
            top, rows = S5_TOP[ch]
        else:
            rows = S5[ch]
        gw = max([len(r) for r in rows] + [len(top) if top else 0])
        if ch == ' ':
            widths.append(3)
            continue
        m = np.zeros((chh, cw), bool)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    m[1 + y, 1 + x] = True
        if top:
            for x, c in enumerate(top):
                if c == '#' or c != '.':
                    m[0, 1 + x] = True
            # forzar el patrón literal de la marca
            m[0, 1:1 + gw] = False
            for x, c in enumerate(top):
                if c == '#':
                    m[0, 1 + x] = True
        dil = ndi.binary_dilation(m, np.ones((3, 3), bool)) & ~m
        cell = np.zeros((chh, cw, 4), np.uint8)
        cell[m] = (255, 255, 255, 255)
        cell[dil] = OUT + (255,)
        r_, c_ = divmod(i, cols)
        sheet[r_ * chh:(r_ + 1) * chh, c_ * cw:(c_ + 1) * cw] = cell
        widths.append(gw + 1)
    save_font('font_s', sheet, dict(cellW=cw, cellH=chh, cols=cols, chars=CHARS, widths=widths, baseline=8, spacing=1))


