def E(cx, cy, rx, ry, a0=0, a1=360, n=28):
    pts = []
    for k in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * k / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


