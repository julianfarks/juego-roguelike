def acc(base, mark, row_off=0, cap=False, ch=None):
    rows = list(S5[base])
    rows = [r.ljust(max(len(x) for x in S5[base]), '.') for r in rows]
    w = len(rows[0])
    if cap:
        top = list(mark)
        return ['.' * w if False else t.ljust(w, '.')[:w] for t in top] + rows
    for i, mrow in enumerate(mark):
        rows[row_off + i] = mrow.ljust(w, '.')[:w]
    return rows


# mayúsculas acentuadas: marca en la fila 0 del celda (una fila extra encima)
S5_TOP = {}   # glyph rows with top extra row (index -1)
for ch, base, mk in (('Á', 'A', '..#..'), ('É', 'E', '..#..'), ('Í', 'I', '..#'), ('Ó', 'O', '..#..'), ('Ú', 'U', '..#..'), ('Ñ', 'N', '##.#.'), ('Ü', 'U', '#...#')):
    S5_TOP[ch] = (mk, S5[base])
