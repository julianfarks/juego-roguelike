def pen_mask(strokes, SS=8, W=20, H=16, L=2.5, ang=24, base=0.95):
    im = Image.new('L', (W * SS, H * SS), 0)
    dr = ImageDraw.Draw(im)
    nx, ny = math.cos(math.radians(ang)) * L / 2, -math.sin(math.radians(ang)) * L / 2
    for pts in strokes:
        if len(pts) == 1:
            pts = [pts[0], pts[0]]
        for a, b in zip(pts[:-1], pts[1:]):
            P = lambda p, s: ((p[0] + s * nx) * SS, (p[1] + s * ny) * SS)
            dr.polygon([P(a, 1), P(a, -1), P(b, -1), P(b, 1)], fill=255)
            dr.line([(a[0] * SS, a[1] * SS), (b[0] * SS, b[1] * SS)], fill=255, width=max(1, int(base * SS)))
        a = pts[0]
        dr.ellipse([a[0] * SS - base * SS / 2, a[1] * SS - base * SS / 2, a[0] * SS + base * SS / 2, a[1] * SS + base * SS / 2], fill=255)
        a = pts[-1]
        dr.ellipse([a[0] * SS - base * SS / 2, a[1] * SS - base * SS / 2, a[0] * SS + base * SS / 2, a[1] * SS + base * SS / 2], fill=255)
    arr = np.array(im).reshape(H, SS, W, SS).mean((1, 3)) / 255.0
    return arr >= 0.5


def accent_strokes(kind, cx, cap):
    y = 1.0 if cap else 3.0
    if kind == 'acute':
        return [[(cx - 0.8, y + 1.5), (cx + 1.0, y)]]
    if kind == 'tilde':
        return [[(cx - 2.6, y + 1.5), (cx - 0.9, y + 0.1), (cx + 0.9, y + 1.5), (cx + 2.6, y + 0.1)]]
    return [[(cx - 1.6, y + 0.6), (cx - 1.6, y + 1.0)], [(cx + 1.6, y + 0.6), (cx + 1.6, y + 1.0)]]


def scale_x(strokes, f):
    return [[(x * f, y) for x, y in pts] for pts in strokes]


def glyph_mask(ch):
    for f in (1.0, 0.94, 0.9, 0.86, 0.82, 0.78):
        if ch in ACC:
            base, kind = ACC[ch]
            b = scale_x(G[base], f)
            if base.isupper():
                b = [[(x, B - (B - y) * 0.84) for x, y in pts] for pts in b]
            m0 = pen_mask(b)
            xs = np.where(m0.any(0))[0]
            cx = (xs.min() + xs.max() + 1) / 2
            m = pen_mask(b + accent_strokes(kind, cx, base.isupper()))
        else:
            m = pen_mask(scale_x(G[ch], f))
        xs = np.where(m.any(0))[0]
        if xs.max() - xs.min() + 1 <= 10:
            break
    return m


def build_big():
    cw, chh, cols = 12, 16, 16
    rows_n = (len(CHARS) + cols - 1) // cols
    sheet = np.zeros((rows_n * chh, cols * cw, 4), np.uint8)
    widths = []
    for i, ch in enumerate(CHARS):
        if ch == ' ':
            widths.append(5)
            continue
        m = glyph_mask(ch)
        xs = np.where(m.any(0))[0]
        shift = 1 - xs.min()
        m = np.roll(m, shift, 1)
        xs = xs + shift
        gw = xs.max() + 1
        if gw > 11:
            print('aviso: glifo ancho', ch, gw)
        m = m[:, :cw]
        dil = ndi.binary_dilation(m, np.ones((3, 3), bool)) & ~m
        cell = np.zeros((chh, cw, 4), np.uint8)
        # relleno blanco con leve gradiente vertical para dar cuerpo (el motor tiñe)
        ys_ = np.arange(chh)[:, None] * np.ones((1, cw))
        shade = np.clip(255 - (ys_ - 3) * 2.2, 205, 255).astype(np.uint8)
        for c in range(3):
            cell[..., c][m] = shade[m]
        cell[m, 3] = 255
        cell[dil] = OUT + (255,)
        r_, c_ = divmod(i, cols)
        sheet[r_ * chh:(r_ + 1) * chh, c_ * cw:(c_ + 1) * cw] = cell
        widths.append(int(min(gw + 1, cw - 1)))
    save_font('font_b', sheet, dict(cellW=cw, cellH=chh, cols=cols, chars=CHARS, widths=widths, baseline=13, spacing=1))


def render_text(fontname, text, scale=3, tint=(255, 255, 255)):
    im = Image.open(A + '/font/' + fontname + '.png').convert('RGBA')
    j = json.load(open(A + '/font/' + fontname + '.json'))
    cw, chh, cols = j['cellW'], j['cellH'], j['cols']
    W = sum(j['widths'][j['chars'].index(c)] + j['spacing'] for c in text if c in j['chars']) + 4
    out = Image.new('RGBA', (W, chh + 2), (0, 0, 0, 0))
    x = 1
    for c in text:
        if c not in j['chars']:
            continue
        k = j['chars'].index(c)
        cell = im.crop(((k % cols) * cw, (k // cols) * chh, (k % cols) * cw + cw, (k // cols) * chh + chh))
        if tint != (255, 255, 255):
            a = np.array(cell).astype(float)
            wh = (a[..., 0] > 200) & (a[..., 3] > 0)
            a[wh, :3] = a[wh, :3] * np.array(tint) / 255
            cell = Image.fromarray(a.astype(np.uint8), 'RGBA')
        out.alpha_composite(cell, (x, 1))
        x += j['widths'][k] + j['spacing']
    return out.resize((out.width * scale, out.height * scale), Image.NEAREST)


